/**
 * Saved dashboards. Dashboard-level time range and refresh are inherited by every widget
 * that does not override them. A custom range uses `time_from`/`time_to`; presets resolve
 * against the organisation timezone at query time.
 */
export const dashboard = pgTable(
  "dashboards",
  {
    id: text("id").primaryKey(),
    organizationId: text("organization_id")
      .notNull()
      .references(() => organization.id, { onDelete: "cascade" }),
    name: text("name").notNull(),
    description: text("description"),
    scope: text("scope").notNull(),
    locationId: text("location_id"),
    deviceId: text("device_id"),
    createdBy: text("created_by").references(() => user.id, {
      onDelete: "set null",
    }),
    visibility: text("visibility").default("organisation").notNull(),
    isDefault: boolean("is_default").default(false).notNull(),
    timeRange: text("time_range").default("24h").notNull(),
    timeFrom: timestamp("time_from", { withTimezone: true }),
    timeTo: timestamp("time_to", { withTimezone: true }),
    refreshSeconds: integer("refresh_seconds").default(60).notNull(),
    createdAt: timestamp("created_at", { withTimezone: true })
      .defaultNow()
      .notNull(),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .defaultNow()
      .$onUpdate(() => /* @__PURE__ */ new Date())
      .notNull(),
  },
  (table) => [
    unique("dashboards_organization_id_id_unique").on(
      table.organizationId,
      table.id,
    ),
    foreignKey({
      name: "dashboards_location_same_organization_fk",
      columns: [table.organizationId, table.locationId],
      foreignColumns: [location.organizationId, location.id],
    }).onDelete("cascade"),
    foreignKey({
      name: "dashboards_device_same_organization_fk",
      columns: [table.organizationId, table.deviceId],
      foreignColumns: [device.organizationId, device.id],
    }).onDelete("cascade"),
    check(
      "dashboards_scope_check",
      sql`${table.scope} in ('organisation', 'location', 'device')`,
    ),
    check(
      "dashboards_visibility_check",
      sql`${table.visibility} in ('private', 'organisation')`,
    ),
    check(
      "dashboards_scope_target_check",
      sql`(${table.scope} = 'organisation' and ${table.locationId} is null and ${table.deviceId} is null)
        or (${table.scope} = 'location' and ${table.locationId} is not null and ${table.deviceId} is null)
        or (${table.scope} = 'device' and ${table.deviceId} is not null and ${table.locationId} is null)`,
    ),
    check(
      "dashboards_custom_range_check",
      sql`(${table.timeRange} = 'custom') = (${table.timeFrom} is not null and ${table.timeTo} is not null)
        and (${table.timeFrom} is null or ${table.timeFrom} < ${table.timeTo})`,
    ),
    check(
      "dashboards_refresh_check",
      sql`${table.refreshSeconds} = 0 or ${table.refreshSeconds} between 10 and 3600`,
    ),
    // At most one default dashboard per scope target.
    uniqueIndex("dashboards_default_unique")
      .on(
        table.organizationId,
        table.scope,
        sql`coalesce(${table.locationId}, ${table.deviceId}, '')`,
      )
      .where(sql`${table.isDefault}`),
    index("dashboards_organization_scope_idx").on(
      table.organizationId,
      table.scope,
    ),
  ],
);

