/**
 * A user's delegation to Vera for one external identity (one WhatsApp number).
 * Vera presents the grant token on every call; only its SHA-256 hash is stored, and
 * setting `revoked_at` blocks the very next call.
 */
export const integrationGrant = pgTable(
  "integration_grants",
  {
    id: text("id").primaryKey(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    organizationId: text("organization_id").references(() => organization.id, {
      onDelete: "set null",
    }),
    channel: text("channel").notNull(),
    tokenHash: text("token_hash").notNull().unique(),
    // SHA-256 of the normalised external id (E.164 phone number); one live grant per number.
    externalIdHash: text("external_id_hash").notNull(),
    // Masked external identity shown in the UI, e.g. "+91 •••••••321".
    externalLabel: text("external_label").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true })
      .defaultNow()
      .notNull(),
    lastUsedAt: timestamp("last_used_at", { withTimezone: true }),
    revokedAt: timestamp("revoked_at", { withTimezone: true }),
  },
  (table) => [
    check(
      "integration_grants_channel_check",
      sql`${table.channel} in ('whatsapp')`,
    ),
    index("integration_grants_user_id_idx").on(table.userId),
    uniqueIndex("integration_grants_live_external_id_unique")
      .on(table.channel, table.externalIdHash)
      .where(sql`${table.revokedAt} is null`),
  ],
);

